async def test_real_api_via_mcp_with_fake_inference(monkeypatch):
    pipeline, recognizer = FakePipeline(), FakeRecognizer()
    app = create_app(ApiSettings(api_tokens="upstream-only:test"), pipeline, recognizer)
    previous = VLLM_UP._value.get()
    settings = Settings(
        _env_file=None,
        api_tokens_raw="inbound-only:test",
        upstream_client_token="upstream-only",
    )
    server, ctx = build_server(settings, transport=httpx.ASGITransport(app=app))
    try:
        VLLM_UP.set(1)
        async with Client(server) as client:
            parsed = await client.call_tool(
                "ocr_parse_document",
                {
                    "params": {
                        "image_base64": PNG,
                        "output": "both",
                        "dpi": 150,
                    }
                },
            )
            assert not parsed.is_error
            assert parsed.structured_content["pages"][0]["markdown"] == "# Fixture"
            assert any(
                w["code"] == "dpi_ignored"
                for w in parsed.structured_content["warnings"]
            )
            assert len(pipeline.calls) == 1
            for task in ELEMENT_TASKS:
                result = await client.call_tool(
                    "ocr_recognize_image",
                    {"params": {"image_base64": PNG, "task": task}},
                )
                assert not result.is_error
                assert result.structured_content["task"] == task
                if task == "spotting":
                    assert result.structured_content["boxes"] == [[1, 2, 3, 4]]
            assert recognizer.tasks == list(ELEMENT_TASKS)
            metrics = await client.read_resource("ocr://metrics")
            assert "ocr_" in metrics.contents[0].text
    finally:
        VLLM_UP.set(previous)
        await ctx.client.aclose()


