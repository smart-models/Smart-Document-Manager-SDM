async def test_public_bootstrap_protected_data_and_headless_mode():
    for exposed in (True, False):
        settings = ApiSettings(api_tokens="never-in-bootstrap:test", expose_frontend=exposed)
        app = create_app(settings, FakePipeline(), FakeRecognizer())
        schema = app.openapi()
        assert (
            schema["components"]["securitySchemes"]["BearerAuth"]["scheme"] == "bearer"
        )
        assert schema["paths"]["/stats"]["get"]["security"] == [{"BearerAuth": []}]
        assert "security" not in schema["paths"]["/health"]["get"]
        assert (
            "text/plain"
            in schema["paths"]["/metrics"]["get"]["responses"]["200"]["content"]
        )
        async with httpx.AsyncClient(
            transport=httpx.ASGITransport(app), base_url="http://test"
        ) as client:
            for path in ("/", "/assets/config.js", "/assets/style.css"):
                response = await client.get(path)
                assert response.status_code == (200 if exposed else 404)
                assert "never-in-bootstrap" not in response.text
            assert (await client.get("/health")).status_code == 200
            for method, path in (
                ("GET", "/stats"),
                ("GET", "/metrics"),
                ("POST", "/parse"),
                ("POST", "/ocr"),
            ):
                assert (await client.request(method, path)).status_code == 401
            for path in ("/stats", "/metrics"):
                assert (
                    await client.get(
                        path, headers={"Authorization": "Bearer never-in-bootstrap"}
                    )
                ).status_code == 200
    assert not load_settings({"EXPOSE_FRONTEND": "false"}, None).expose_frontend


