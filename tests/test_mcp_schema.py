@pytest.mark.parametrize(
    "sources,valid",
    [
        ({}, False),
        ({"image_base64": None}, False),
        ({"image_base64": "   "}, False),
        ({"image_base64": PNG}, True),
        ({"image_base64": PNG, "pdf_base64": None}, True),
        ({"image_base64": PNG, "pdf_base64": " \t"}, True),
        ({"image_base64": PNG, "pdf_base64": "JVBERi0="}, False),
    ],
)
def test_openapi_exactly_one_useful_json_source(sources, valid):
    from jsonschema import Draft202012Validator

    app = create_app(ApiSettings(max_pages=7), FakePipeline(), FakeRecognizer())
    schema = app.openapi()["paths"]["/parse"]["post"]["requestBody"]["content"][
        "application/json"
    ]["schema"]
    validator = Draft202012Validator(schema)
    assert validator.is_valid(sources) == valid
    assert not validator.is_valid({"image_base64": PNG, "max_pages": 8})
    assert validator.is_valid({"image_base64": PNG, "max_pages": 7})
    # The tool intentionally delegates its upper bound to the deployment.
    assert all(
        "maximum" not in branch
        for branch in ParseDocumentInput.model_json_schema()["properties"]["max_pages"][
            "anyOf"
        ]
    )


