class FakePipeline:
    """Record image inputs and return deterministic empty structured pages."""

    def __init__(self):
        self.calls = []

    async def parse_document(
        self,
        images,
        lanes,
        page_timeout,
        timeout,
        *,
        close_images=False,
        on_page=None,
        dpi=None,
        reread=False,
    ):
        self.calls.append(images)
        if close_images:
            for image in images:
                if hasattr(image, "close"):
                    image.close()
        pages = [
            {
                "markdown": "# Fixture",
                "blocks": [],
                "images": [],
                "width": 1,
                "height": 1,
                "elapsed": 0.001,
            }
            for _ in images
        ]
        for page in pages:
            if on_page is not None:
                on_page(page)
        return pages


class FakeRecognizer:
    """Record recognition tasks and return deterministic task-specific text."""

    def __init__(self):
        self.tasks = []

    async def recognize(self, image, task, timeout):
        self.tasks.append(task)
        text = "fixture [[1,2,3,4]]" if task == "spotting" else "fixture"
        return CompletionResult(text, "stop")


@pytest.mark.parametrize(
    "path,model",
    [
        ("/parse", ParseDocumentInput),
        ("/ocr", RecognizeImageInput),
    ],
)
def test_upload_fields_types_constraints_and_defaults_match_tools(path, model):
    app = create_app(ApiSettings(), FakePipeline(), FakeRecognizer())
    operation = app.openapi()["paths"][path]["post"]
    content = operation["requestBody"]["content"]
    assert set(content) == {"application/json", "multipart/form-data"}
    # filename is shared so archive naming is consistent.
    properties = content["application/json"]["schema"]["properties"]
    tool_properties = model.model_json_schema()["properties"]
    # progress_id is generated by the MCP tool, never supplied by its caller.
    generated = {"progress_id"} if path == "/parse" else set()
    assert (
        set(properties)
        == set(tool_properties) - {"file_path", "response_format"} | generated
    )
    for name, field in properties.items():
        if name in generated:
            continue
        other = tool_properties[name]
        # Source exclusivity is a tool guard; API source requiredness is tested below.
        if name in {"image_base64", "pdf_base64", "document_base64"}:
            continue
        for key in ("type", "enum", "default", "minimum", "maximum"):
            assert field.get(key) == other.get(key), name
        if "anyOf" in field:
            upstream_alternatives = [
                {k: v for k, v in x.items() if k != "maximum" or name != "max_pages"}
                for x in field["anyOf"]
            ]
            assert upstream_alternatives == other["anyOf"], name
    multipart = content["multipart/form-data"]["schema"]["properties"]
    api_only = {"filename", "progress_id"} if path == "/parse" else set()
    assert set(multipart) == set(properties) | {"file"} | api_only
    assert multipart["file"] == {"type": "string", "format": "binary"}
    if path == "/ocr":
        assert set(properties["task"]["enum"]) == set(ELEMENT_TASKS)


